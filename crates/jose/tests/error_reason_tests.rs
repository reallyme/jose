#[test]
fn wire_construction_error_is_schema_mapped() {
    let error = reallyme_jose::wire::JoseWireErrorConstructionError::BranchReasonMismatch;
    assert_eq!(error.reason(), JoseErrorReason::BackendInternal);
}

