import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { schemaMessages } from "./read-proto-schema.mjs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
function implementation(source, marker) {
  const start = source.indexOf(marker);
  const end = source.indexOf("\n}\n", start);
  if (start < 0 || end < 0) throw new TypeError("native cleanup implementation missing");
  return source.slice(start, end);
}

export function assertProtobufHardening({ schema, owned, views,
  oneofs = read("crates/proto/src/generated/buffa/reallyme.jose.v1.jose.__oneof.rs"),
  config = read("buf.gen.yaml"),
}) {
  for (const option of ["local: protoc-gen-reallyme-buffa", "strategy: all", "zeroize_in=.reallyme.jose.v1",
    "borrowed_views_only_in=.reallyme.jose.v1", "unknown_fields=false", "deny_unknown_json_fields=true", "bytes_type_custom_in=.reallyme.jose.v1=crate::SecretBytes",
    "string_type_custom_in=.reallyme.jose.v1=crate::SecretString", "json_policy_type=crate::SecretBytes", "json_policy_type=crate::SecretString"]) {
    if (!config.includes(option)) throw new TypeError("native cleanup configuration missing");
  }
  if (!owned.startsWith("// @generated by reallyme-buffa-codegen 0.1.2.")) throw new TypeError("wrong Buffa generator output");
  if (owned.includes("__buffa_unknown_fields") || owned.includes("crate::merge_sensitive::") || owned.includes("__reallyme_")) {
    throw new TypeError("obsolete generated-source workaround remains");
  }
  if (/\bHasMessageView\b/u.test(owned) || /\b(?:HasMessageView|OwnedView)\b/u.test(views)) {
    throw new TypeError("guarded messages must use borrowed generated views");
  }
  const messages = schemaMessages(schema);
  const compactOwned = owned.replace(/\s+/gu, "");
  const compactViews = views.replace(/\s+/gu, "");
  const oneofCount = messages.reduce((count, { body }) => count + [...body.matchAll(/\boneof\s+\w+\s*\{/gu)].length, 0);
  const oneofDrops = [...oneofs.matchAll(/impl ::core::ops::Drop for \w+ \{/gu)].length;
  if (oneofDrops !== oneofCount) throw new TypeError("native oneof cleanup coverage differs from the schema");
  for (const { name, body } of messages) {
    const wipe = implementation(owned, `impl ::buffa::sensitive::Zeroize for ${name} {`);
    const drop = implementation(owned, `impl ::core::ops::Drop for ${name} {`);
    if (!drop.includes("Zeroize::zeroize(self)")) throw new TypeError("native drop does not invoke cleanup");
    if (!compactOwned.includes(`impl::buffa::sensitive::ZeroizeOnDropfor${name}{}`) ||
        !compactViews.includes(`impl<'a>::buffa::sensitive::ZeroizeOnDropfor${name}View<'a>{}`)) {
      throw new TypeError("message or view lacks native cleanup ownership");
    }
    const deserialize = implementation(owned, `impl<'de> ::serde::Deserialize<'de> for ${name} {`);
    if (!deserialize.replace(/\s+/gu, "").replace("letmut__r", "let__r").includes(`let__r=<${name}as::core::default::Default>::default();`) ||
        !deserialize.includes("JsonErrorReason::UnknownField")) throw new TypeError(`JSON admission lacks early cleanup owner or strict rejection: ${name}`);
    const structure = implementation(owned, `pub struct ${name} {`);
    const cleanFields = wipe.replace(/\s+/gu, "").replaceAll(",)", ")");
    for (const [, field] of body.matchAll(/\boneof\s+(\w+)\s*\{/gu)) {
      if (!cleanFields.includes(`Zeroize::zeroize(&mutself.${field})`)) throw new TypeError("message does not wipe its oneof");
    }
    for (const [, cardinality, type, field] of body.replace(/oneof\s+\w+\s*\{[\s\S]*?\}/gu, "").matchAll(/^\s*(?:(optional|repeated)\s+)?(\w+)\s+(\w+)\s*=/gmu)) {
      if (!cleanFields.includes(`Zeroize::zeroize(&mutself.${field})`)) throw new TypeError(`native cleanup omits a field: ${name}.${field}`);
      const declaration = new RegExp(`pub ${field}: ([^,]+),`, "u").exec(structure)?.[1] ?? "";
      if (cardinality === "repeated" && !declaration.includes("::buffa::sensitive::List<")) {
        throw new TypeError("repeated field lacks guarded storage");
      }
      if (type === "bytes" || type === "string") {
        if (!declaration.includes(type === "bytes" ? "crate::SecretBytes" : "crate::SecretString")) throw new TypeError("unguarded scalar storage");
      }
    }
    for (const [source, marker] of [[owned, `impl ::core::fmt::Debug for ${name} {`], [views, `impl<'a> ::core::fmt::Debug for ${name}View<'a> {`]]) {
      const debug = implementation(source, marker);
      if (debug.includes("&self.") || !debug.includes("REDACTED") && /\b\w+\s+\w+\s*=/u.test(body)) throw new TypeError("native diagnostics expose fields");
    }
  }
}

export function checkProtobufHardening() {
  assertProtobufHardening({ schema: read("crates/proto/proto/reallyme/jose/v1/jose.proto"),
    owned: read("crates/proto/src/generated/buffa/reallyme.jose.v1.jose.rs"),
    views: read("crates/proto/src/generated/buffa/reallyme.jose.v1.jose.__view.rs") });
}
if (process.argv[1] === fileURLToPath(import.meta.url)) checkProtobufHardening();
