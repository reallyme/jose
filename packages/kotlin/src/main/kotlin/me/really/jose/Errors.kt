    JWS_INVALID_COMPACT(100), JWS_INPUT_TOO_LARGE(101), JWS_LENGTH_OVERFLOW(102),
    JWS_INVALID_PAYLOAD_UTF8(103), JWS_BAD_PAYLOAD_BASE64(104), JWS_BAD_HEADER_BASE64(120),
    JWS_BAD_HEADER_UTF8(121),
    JWS_HEADER_MISMATCH(122), JWS_BAD_SIGNATURE_BASE64(140), JWS_BAD_RAW_SIGNATURE(141),
    JWS_INVALID_SIGNATURE(142), JWS_SIGN_FAILED(160), JWS_BAD_DER_SIGNATURE(161),
    JWE_INVALID_COMPACT(200), JWE_INPUT_TOO_LARGE(201), JWE_INVALID_ENCODING(202),
    JWE_INVALID_HEADER(220), JWE_UNSUPPORTED_KEY_MANAGEMENT_ALGORITHM(221),
    JWE_UNSUPPORTED_CONTENT_ENCRYPTION_ALGORITHM(222), JWE_MISSING_REQUIRED_HEADER_PARAMETER(223),
    JWE_HEADER_POLICY_MISMATCH(224), JWE_KID_POLICY_MISMATCH(225), JWE_APU_POLICY_MISMATCH(226),
    JWE_APV_POLICY_MISMATCH(227), JWE_INVALID_ENCRYPTED_KEY(240),
    JWE_INVALID_CONTENT_ENCRYPTION_KEY(241), JWE_INVALID_CONTENT_CIPHER_INPUT(242),
