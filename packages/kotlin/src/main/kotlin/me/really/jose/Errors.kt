    internal companion object {
        private val byCode: Map<Int, ReallyMeJoseErrorReason> = entries.associateBy { it.code }

        fun fromCode(code: Int): ReallyMeJoseErrorReason? = byCode[code]
    }
}

/** Audit-safe JVM exceptions. No variant contains secrets, PII, paths, or backend text. */
public sealed class ReallyMeJoseException(message: String) : RuntimeException(message) {
    public class JoseFailure(
        public val branch: ReallyMeJoseErrorBranch,
        public val reason: ReallyMeJoseErrorReason,
    ) : ReallyMeJoseException("JOSE operation failed")

    public class InvalidInput : ReallyMeJoseException("invalid input")

    public class NativeProviderFailure : ReallyMeJoseException("native provider failure")

    public class MalformedProviderResponse : ReallyMeJoseException("malformed provider response")
}
